def test_parse_os_release_cachy_and_mint() -> None:
    cachy = machine_sheet.parse_os_release(_CACHY_OS_RELEASE)
    assert cachy["ID"] == "cachyos"
    assert cachy["PRETTY_NAME"] == "CachyOS"
    assert cachy["ID_LIKE"] == "arch"
    mint = machine_sheet.parse_os_release(_MINT_OS_RELEASE)
    assert mint["ID"] == "linuxmint"
    assert mint["PRETTY_NAME"] == "Linux Mint 22.1"
    assert mint["VERSION_ID"] == "22.1"


def test_parse_os_release_skips_comments_and_blank() -> None:
    data = machine_sheet.parse_os_release("# comment\n\nID=arch\n")
    assert data == {"ID": "arch"}


def test_parse_meminfo_kib_to_bytes() -> None:
    mem = machine_sheet.parse_meminfo(_MEMINFO)
    assert mem["MemTotal"] == 32802432 * 1024
    assert mem["MemAvailable"] == 21456780 * 1024
    assert mem["SwapTotal"] == 8388608 * 1024
    ram = machine_sheet.ram_from_meminfo(mem)
    assert ram["total_gib"] == round(32802432 / 1024 / 1024, 2)
    used = 32802432 - 21456780
    assert ram["used_gib"] == round(used / 1024 / 1024, 2)
    assert ram["percent"] == round((used / 32802432) * 100, 1)


def test_parse_df_p_keeps_useful_mounts() -> None:
    mounts = machine_sheet.parse_df_p(_DF_P)
    points = [row["mountpoint"] for row in mounts]
    assert "/" in points
    assert "/home" in points
    assert "/mnt/data" in points
    assert "/tmp" not in points
    assert "/dev" not in points
    assert "/root" not in points
    assert "/var/log" not in points
    assert "/dev/shm" not in points
    assert "/var/lib/docker/overlay2" not in points
    assert "/snap/core/1" not in points
    root = next(row for row in mounts if row["mountpoint"] == "/")
    assert root["percent"] == 19.0
    assert root["fstype"] == ""
    assert root["device"] == "/dev/nvme0n1p2"
    assert root["total_kib"] == 479711192
    assert root["used_kib"] == 86000000
    assert root["avail_kib"] == 369000000


