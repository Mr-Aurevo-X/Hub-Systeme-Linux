def test_assemble_sheet_from_raw_bundle() -> None:
    raw = {
        "os_release": _CACHY_OS_RELEASE,
        "meminfo": _MEMINFO,
        "df": _DF_P,
        "cpuinfo": _CPUINFO,
        "resolv": _RESOLV,
        "route": _PROC_ROUTE,
        "ip_route": _IP_ROUTE,
        "hostname": "atelier-cachy",
        "kernel": "Linux 6.16.1-cachyos",
        "machine": "x86_64",
        "timezone": "Europe/Paris",
        "datetime": "2026-08-18 11:00:00",
        "uptime_s": 3661,
        "gpu": {"available": True, "devices": [{"vendor": "AMD", "name": "Radeon"}]},
            "interfaces": [
                {"name": "enp2s0", "ipv4": ["192.168.0.10"], "ipv6": [], "is_up": True},
                {"name": "lo", "ipv4": ["127.0.0.1"], "ipv6": ["::1"], "is_up": True},
                {"name": "vethdb6fd8e", "ipv4": [], "ipv6": ["fe80::1"], "is_up": True},
                {"name": "docker0", "ipv4": ["172.17.0.1"], "ipv6": [], "is_up": True},
            ],
        "pacman_qu": _PACMAN_QU,
        "apt_upgradable": "",
        "snapshots": {"detected": True, "backend": "snapper"},
    }
    sheet = machine_sheet.assemble_sheet(raw)
    assert sheet["identity"]["hostname"] == "atelier-cachy"
    assert sheet["identity"]["pretty_name"] == "CachyOS"
    assert sheet["identity"]["os_id"] == "cachyos"
    assert sheet["cpu"]["model"].startswith("AMD Ryzen")
    assert sheet["cpu"]["logical_cores"] == 3
    assert sheet["ram"]["total_gib"] > 30
    assert any(m["mountpoint"] == "/" for m in sheet["storage"])
    assert sheet["network"]["gateway"] == "192.168.1.1"
    assert sheet["network"]["dns"] == ["1.1.1.1", "9.9.9.9"]
    names = [item.get("name") for item in sheet["network"]["interfaces"]]
    assert names == ["enp2s0"]
    assert sheet["updates"]["pending"] == 2
    assert sheet["snapshots"]["detected"] is True
    text = machine_sheet.to_text(sheet)
    assert "atelier-cachy" in text
    assert "CachyOS" in text
    payload = json.loads(machine_sheet.to_json(sheet))
    assert payload["identity"]["hostname"] == "atelier-cachy"
    csv_text = machine_sheet.to_csv(sheet)
    assert csv_text.splitlines()[0].startswith("section,key,value")
    assert "identity,hostname,atelier-cachy" in csv_text


def test_collect_inventory_raw_reads_local_proc() -> None:
    from core import host_probe

    raw = host_probe.collect_inventory_raw()
    assert "MemTotal" in raw["meminfo"]
    assert "=" in raw["os_release"]
    sheet = machine_sheet.assemble_sheet(raw)
    assert sheet["identity"]["arch"]
    assert isinstance(sheet["storage"], list)


def test_assemble_sheet_empty_raw_is_safe() -> None:
    sheet = machine_sheet.assemble_sheet({})
    assert sheet["identity"]["hostname"] == ""
    assert sheet["updates"]["pending"] == 0
    assert sheet["snapshots"]["detected"] is False
    assert machine_sheet.to_csv(sheet).startswith("section,key,value")
